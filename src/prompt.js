function formatSeminarContext(sessionContext) {
    return [
        `参加形式: ${sessionContext.format || "未選択"}`,
        `参加タイミング: ${sessionContext.timing || "未選択"}`,
        `温度感: ${sessionContext.mood || "未選択"}`
    ].join("\n");
}

